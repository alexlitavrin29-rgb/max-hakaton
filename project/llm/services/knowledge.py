def benefit_card(fields):
    text, tasks, sources = CARDS["benefits"]
    notes = []
    if fields.get("family_status") == "adopted":
        notes.append("При усыновлении меры для детей-сирот нельзя автоматически переносить на ребёнка: основание каждой меры нужно уточнять отдельно.")
    elif fields.get("family_status") in {"guardian", "foster"}:
        notes.append("Для опеки или приёмной семьи отдельно уточняются поддержка ребёнка и выплаты взрослому, который его воспитывает.")
    elif fields.get("family_status") == "graduate":
        notes.append("После выпуска стоит проверить документы, подтверждающие статус, и продолжение уже назначенной поддержки.")
    study = fields.get("study", "").lower()
    if not study or any(word in study for word in ("не уч", "неуч", "работаю")):
        text = text.replace("• Поддержка во время учёбы — в учебном заведении.\n", "")
        sources = [key for key in sources if key != "education"]
    if fields.get("age") is not None and fields["age"] < 18:
        notes.append("Отдельный вопрос к ведомству — что нужно проверить перед совершеннолетием.")
    return (text + ("\n\n" + "\n".join(notes) if notes else ""), tasks, sources)


