def configure_free_work(config):
    """Upgrade existing draft content without reimporting or publishing the seed."""
    from copy import deepcopy
    config=deepcopy(config)
    if config.get('search',{}).get('contract_version',0)<2:config=configure_work(config)
    config['search']['contract_version']=3
    branch=next(b for b in config['branches'] if b['id']=='work')
    branch['status']='draft'  # Live acceptance gate is separate from unit-test success.
    branch['prompt']=('Извлекай все явно названные новые условия из всей реплики. Сохраняй специализацию профессии. '
        'Тип занятости не является профессией; подработка — частичная занятость. '
        'В коротком уточнении возвращай только новые слова, без копирования прошлой суммы или старого evidence. '
        'Возраст, опыт и образование относятся к соискателю: в родительском запросе к ребёнку, если явно не сказано «для себя». '
        'Отделяй желаемую работу от прошлой, исключённой, профессии родителя и образования. '
        'Прежняя должность не сообщает длительность опыта, обучение специальности — уровень диплома. '
        'Для зарплаты сохраняй фразу целиком: минимум, максимум, диапазон или ориентир, период и налоги. '
        'Не назначай профессию, сумму, период, город и код региона. Справочники проверяет код. '
        'Неизвестное, неважное и требующее уточнения различаются. Спорное исправление не стирает прежние условия. '
        'Несколько альтернатив требуют выбора одного или явного решения искать во всех. '
        'Город уточняется до поиска, возраст спрашивается один раз с возможностью отказа. '
        'Неполная карточка не подтверждает соответствие. При сбое сохранённые условия остаются в диалоге.')
    config['ui']['work_city_question']['text']='{conditions}\n\nВ каком населённом пункте или регионе искать работу?'
    config['ui']['work_place_choices']['text']='{conditions}\n\nУточните место поиска: название, регион и при необходимости район.'
    return config


def main():
    import json
    import urllib.request
    from project.llm.services.scenario import validate
    base="http://127.0.0.1:18765"
    with urllib.request.urlopen(base+"/api/state",timeout=10) as response: before=json.load(response)
    config=validate(configure_free_work(before["config"]))
    request=urllib.request.Request(base+"/api/draft",data=json.dumps(dict(config=config,revision=before["revision"]),ensure_ascii=False).encode(),
                                   headers={"Content-Type":"application/json","X-Editor-Request":"local"},method="PUT")
    with urllib.request.urlopen(request,timeout=10) as response: saved=json.load(response)
    with urllib.request.urlopen(base+"/api/state",timeout=10) as response: after=json.load(response)
    assert after["revision"]==saved["revision"] and after["published_id"]==before["published_id"]
    print(json.dumps(dict(revision=after["revision"],published_id=after["published_id"],work_contract=after["config"]["search"]["contract_version"])))


if __name__=="__main__": main()
